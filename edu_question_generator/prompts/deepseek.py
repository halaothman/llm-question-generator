"""Prompt DeepSeek: امتحان جامعي MCQ صعب من جزء المستند."""
from __future__ import annotations

LANGUAGE_RULES_AR = """
- استخدم العربية الفصحى مع مصطلحات تقنية إنجليزية شائعة فقط (مثل CNN, Attention, FLOPs)
- ممنوع تماماً: الأحرف الصينية أو اليابانية أو الكورية أو أي رموز غريبة
- مسموح فقط: العربية، الإنجليزية، الأرقام، وعلامات رياضية شائعة (+ - × ÷ = ^ / ( ) [ ] %)
"""

# قواعد مستوى التفكير المعرفي (تحليل + حساب multi-step، منع الحفظ الميكانيكي)
_COGNITIVE_LEVEL_BLOCK = """
========================
دورك ومستوى التفكير
========================

اعتبر أنك عضو هيئة تدريس تعد **امتحاناً جامعياً نهائياً** من هذا الجزء فقط.

**التوازن المطلوب (مهم):** لا تجعل كل الأسئلة «احسب» فقط. امزج بين:
- **تحليل وتطبيق:** لماذا؟ ماذا يحدث إذا؟ أثر تغيير (Dropout، Loss، Activation، عدد وحدات، overfitting، …).
- **حساب متعدد الخطوات:** يتطلب **فهم المفهوم أولاً** ثم الحساب، ثم **استنتاج** (ذاكرة، overfitting، سرعة تعلم…) — وليس طرح رقمين.

**ممنوع — حساب ميكانيكي:**
- أسئلة = **طرح أو تعويض مباشر** فقط (مثل: vocab_size − max_words = كم كلمة تُتجاهل؟) بدون ربط بسلوك النموذج أو NLP.
- أي سؤال يحلّه طالب **دون فهم LSTM/NLP/التعلم العميق** بمجرد عملية حسابية واحدة.

**ممنوع — تحليل سطحي:**
- أسئلة label=0/1 → «سلبي/إيجابي» فقط، أو تعريف مباشر من النص بجملة واحدة.

**ممنوع — تكرار:**
- **سؤال واحد فقط** لكل «مهارة» (مثلاً: معاملات Embedding مرة واحدة؛ max_words مرة واحدة بزاوية مختلفة).

**شرط الأرقام:** لا تستخدم قيم أمثلة الملف **كما هي** — استخرج المفهوم ثم **سيناريو جديد** بأرقام مختلفة.

**الحل (solution):** مختصر **واثق** — لا تكتب «ربما»، «قد يحدث خطأ»، «لكن عملياً تصبح 0»؛ إن لم تكن متأكداً **لا تضف** السؤال.

لا تكتب سلسلة تفكير — **JSON فقط**.
"""

# تجريد أسماء الدوال/المتغيرات من الكود في صياغة الأسئلة
_CODE_ABSTRACTION_BLOCK = """
========================
تجريد الكود (السؤال والخيارات والحل)
========================

لا تعتمد في صياغة السؤال أو الخيارات أو الحل على أسماء الدوال، أسماء المتغيرات، أسماء الملفات، أسماء الكائنات البرمجية، أو تفاصيل التنفيذ الخاصة بالكود. استبدلها **بوصف وظيفي** للمفهوم أو المرحلة (مثل: مرحلة التنبؤ، خطوة استخراج الميزات، تسلسل الإدخال، النموذج المدرَّب، توزيع الاحتمالات على الفئات).

**مسموح:** المصطلحات العلمية أو أسماء الخوارزميات أو الطبقات أو الدوال الرياضية أو المقاييس إذا كانت جزءاً من **المادة التعليمية** في هذا الجزء (مثل LSTM، ReLU، Dropout، Softmax، BERTScore، CountVectorizer عندما يكون تدريسه **مقصوداً** في المحاضرة).

**ثابت:** جميع القيم الرقمية والمعطيات الحسابية المهمة لحل السؤال — **لا تغيّرها** ولا تحذفها.

❌ «في الدالة pred_class، عند تطبيق argmax…»
✅ «في مرحلة التصنيف، عند اختيار الفئة ذات أعلى احتمال…»

❌ «بعد X_pred = X_pred[:, 1:]…»
✅ «بعد حذف أقدم عنصر من تسلسل الإدخال وإضافة القيمة المتوقّعة الجديدة…»

❌ خيارات = sorted / set / model.predict (حفظ أسماء من الكود)
✅ «ترتيب القائمة» / «تمييز العناصر الفريدة» / «تطبيق النموذج على دفعة جديدة»
"""


def _deepseek_output_format_section(context: str) -> str:
    """قسم صيغة JSON العربية مع حقل type."""
    return f"""حلّل المحتوى داخلياً دون طباعة التحليل، ثم أخرج الأسئلة **فقط** بصيغة JSON دون أي نص خارج JSON.

{{
  "mcq": [
    {{
      "q": "نص السؤال",
      "options": ["", "", "", ""],
      "answer": "الإجابة الصحيحة (نص الخيار)",
      "solution": "تفسير مختصر وواثق (خطوتان كحد أقصى للحساب)",
      "type": "understanding | analysis | computation | application"
    }}
  ]
}}

استخدم حقل "type" فقط بهذه القيم:
- understanding = فهم عميق (ليس حفظ label)
- analysis = تحليل / لماذا / ماذا لو
- computation = حساب **بعد** فهم (multi-step)
- application = تطبيق مفهوم على سيناريو

UPLOADED DOCUMENT:
{context}"""


def build_deepseek_prompt(
    context: str,
    num_questions: int | None = None,
) -> str:
    """تجميع prompt المستخدم لتوليد MCQ صعبة من مقطع واحد.

    Args:
        context: نص المقطع المرفوع.
        num_questions: العدد المطلوب؛ None = حتى 3 أسئلة.
    """
    count_line = (
        f"أخرج **بالضبط {num_questions}** سؤال MCQ من هذا الجزء فقط — لا أكثر ولا أقل."
        if num_questions
        else "أخرج حتى 3 أسئلة MCQ عالية الجودة من هذا الجزء فقط."
    )
    mix_line = ""
    if num_questions and num_questions >= 3:
        comp_max = max(1, num_questions // 3)
        aa_min = max(1, num_questions // 2)
        mix_line = (
            f"- **التوزيع:** على الأقل **{aa_min}** أسئلة `analysis` أو `application` "
            f"(لماذا / ماذا لو / أثر تغيير…)؛ "
            f"وحتى **{comp_max}** من نوع `computation` **multi-step** (فهم ثم حساب ثم استنتاج) — "
            f"**لا** تملأ الباقي بأسئلة طرح أو تعويض ميكانيكي."
        )

    return f"""أنت خبير في تصميم أسئلة الامتحانات الجامعية.
مهمتك: أسئلة امتحان **صعبة** من **هذا الجزء** فقط — كما يضعها أستاذ جامعي (فهم + استدلال + حساب عند الحاجة).

{LANGUAGE_RULES_AR}

{_COGNITIVE_LEVEL_BLOCK}

========================
الهدف لهذا الطلب
========================

{count_line}
{mix_line}
- **كل** الأسئلة بمستوى امتحان جامعي **صعب** — لا أسئلة سهلة أو متوسطة.
- لا تكرّر نفس الفكرة أو نفس «مهارة الحساب» بأرقام مختلفة فقط.

========================
أمثلة على اتجاه جيد
========================

✅ «إذا زاد embedding_dim، كيف يتغير عدد معاملات Embedding وما أثر ذلك على الذاكرة؟» (فهم + حساب + استنتاج)
✅ «لماذا قد يظهر overfitting عند… وماذا يفعل Dropout؟»
❌ «15000 − 2000 = كم كلمة تُتجاهل؟» بدون سياق نموذج
❌ سؤالان منفصلان لحساب معاملات Embedding بنفس الطريقة

========================
قيود المحتوى
========================

{_CODE_ABSTRACTION_BLOCK}

لا نسخ حرفي من النص.
إذا لم يكفِ المحتوى للعدد بجودة عالية، أخرج **عدداً أقل**.

========================
صيغة الامتحان
========================

MCQ: أربعة خيارات، مشتتات منطقية، `solution` قصير وواثق.

========================
المخرجات
========================

{_deepseek_output_format_section(context)}"""


SYSTEM_MESSAGES = {
    "en": (
        "University final exam MCQs in Arabic: mix analysis/application (why, what-if) "
        "with multi-step computation (understand then calculate). "
        "No mechanical subtraction-only items; confident short solutions. JSON only."
    ),
    "ar": (
        "أنت عضو هيئة تدريس تعد امتحاناً نهائياً. "
        "مزيج: تحليل/تطبيق (لماذا، ماذا لو) + حساب multi-step (فهم ثم حساب) — "
        "لا طرح ميكانيكي ولا solution متردد. JSON فقط."
    ),
}


def build_deepseek_system_message(lang: str) -> str:
    """رسالة system حسب لغة المستند (ar → عربي، غير ذلك → إنجليزي)."""
    return SYSTEM_MESSAGES["ar" if lang == "ar" else "en"]
